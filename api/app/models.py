"""SQLAlchemy ORM models.

Every learner owns courses. A course's content (stages, modules, lessons, resources, projects) is generated by the
course builder (services/builder.py) and deleted with the course. Learner-state tables reference content by id.
"""
from __future__ import annotations

from datetime import date, datetime, timezone

from sqlalchemy import JSON, Boolean, Date, DateTime, Float, ForeignKey, Integer, String, Text, UniqueConstraint
from sqlalchemy.orm import Mapped, mapped_column, relationship

from .db import Base


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


# ───────────────────────────── Content ─────────────────────────────
class Course(Base):
    __tablename__ = "courses"
    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    owner_id: Mapped[int] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"), index=True)
    title: Mapped[str] = mapped_column(String(200))
    subject: Mapped[str] = mapped_column(String(200))
    summary: Mapped[str] = mapped_column(Text, default="")
    goal: Mapped[str] = mapped_column(Text, default="")
    level: Mapped[str] = mapped_column(String(20), default="beginner")
    hours_per_week: Mapped[int] = mapped_column(Integer, default=5)
    source_name: Mapped[str] = mapped_column(String(300), default="")
    source_text: Mapped[str] = mapped_column(Text, default="")
    syllabus: Mapped[list] = mapped_column(JSON, default=list)  # every topic found in the learner's material
    status: Mapped[str] = mapped_column(String(16), default="building")  # building | ready | failed
    step: Mapped[str] = mapped_column(String(300), default="")
    progress: Mapped[float] = mapped_column(Float, default=0.0)
    error: Mapped[str | None] = mapped_column(Text, nullable=True)
    used_ai: Mapped[bool] = mapped_column(Boolean, default=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow, onupdate=utcnow)


class Stage(Base):
    __tablename__ = "stages"
    id: Mapped[str] = mapped_column(String(32), primary_key=True)
    course_id: Mapped[int] = mapped_column(ForeignKey("courses.id", ondelete="CASCADE"), index=True)
    order: Mapped[int] = mapped_column(Integer)
    title: Mapped[str] = mapped_column(String(200))
    summary: Mapped[str] = mapped_column(Text, default="")
    modules: Mapped[list[Module]] = relationship(back_populates="stage", order_by="Module.order")


class Module(Base):
    __tablename__ = "modules"
    id: Mapped[str] = mapped_column(String(32), primary_key=True)
    course_id: Mapped[int] = mapped_column(ForeignKey("courses.id", ondelete="CASCADE"), index=True)
    stage_id: Mapped[str] = mapped_column(ForeignKey("stages.id", ondelete="CASCADE"))
    order: Mapped[int] = mapped_column(Integer)
    title: Mapped[str] = mapped_column(String(200))
    summary: Mapped[str] = mapped_column(Text, default="")
    prerequisites: Mapped[list] = mapped_column(JSON, default=list)
    project_id: Mapped[str | None] = mapped_column(String(64), nullable=True)
    search_queries: Mapped[list] = mapped_column(JSON, default=list)
    stage: Mapped[Stage] = relationship(back_populates="modules")
    lessons: Mapped[list[Lesson]] = relationship(back_populates="module", order_by="Lesson.order")


class Lesson(Base):
    __tablename__ = "lessons"
    id: Mapped[str] = mapped_column(String(48), primary_key=True)
    course_id: Mapped[int] = mapped_column(ForeignKey("courses.id", ondelete="CASCADE"), index=True)
    module_id: Mapped[str] = mapped_column(ForeignKey("modules.id", ondelete="CASCADE"))
    order: Mapped[int] = mapped_column(Integer)
    global_order: Mapped[int] = mapped_column(Integer, index=True)
    title: Mapped[str] = mapped_column(String(300))
    level: Mapped[str] = mapped_column(String(20))
    minutes: Mapped[int] = mapped_column(Integer)
    status: Mapped[str] = mapped_column(String(16))  # outline | generating | authored | failed
    gen_error: Mapped[str | None] = mapped_column(Text, nullable=True)
    search_queries: Mapped[list] = mapped_column(JSON, default=list)
    covers: Mapped[list] = mapped_column(JSON, default=list)
    objectives: Mapped[list] = mapped_column(JSON, default=list)
    overview: Mapped[dict] = mapped_column(JSON, default=dict)
    sections: Mapped[list] = mapped_column(JSON, default=list)
    module: Mapped[Module] = relationship(back_populates="lessons")
    exercise: Mapped[Exercise | None] = relationship(back_populates="lesson", uselist=False)
    questions: Mapped[list[Question]] = relationship(back_populates="lesson", order_by="Question.order")
    flashcards: Mapped[list[Flashcard]] = relationship(back_populates="lesson")
    resource_links: Mapped[list[LessonResource]] = relationship(back_populates="lesson", order_by="LessonResource.order")


class Resource(Base):
    __tablename__ = "resources"
    id: Mapped[str] = mapped_column(String(64), primary_key=True)
    course_id: Mapped[int] = mapped_column(ForeignKey("courses.id", ondelete="CASCADE"), index=True)
    source: Mapped[str] = mapped_column(String(20), default="web")  # hackernews | wikipedia | openlibrary | arxiv | youtube | web
    score: Mapped[int | None] = mapped_column(Integer, nullable=True)  # Hacker News points, ratings count, ...
    comments: Mapped[int | None] = mapped_column(Integer, nullable=True)
    discussion_url: Mapped[str | None] = mapped_column(String(600), nullable=True)
    rating: Mapped[float | None] = mapped_column(Float, nullable=True)
    recommended_by: Mapped[int | None] = mapped_column(Integer, nullable=True)  # commenters recommending it in Ask HN threads
    title: Mapped[str] = mapped_column(String(400))
    provider: Mapped[str] = mapped_column(String(200))
    type: Mapped[str] = mapped_column(String(20), index=True)
    level: Mapped[str] = mapped_column(String(20))
    duration: Mapped[str] = mapped_column(String(40))
    language: Mapped[str] = mapped_column(String(20), default="en")
    cost: Mapped[str] = mapped_column(String(20))
    url: Mapped[str] = mapped_column(String(600))
    why: Mapped[str] = mapped_column(Text)
    authors: Mapped[str | None] = mapped_column(String(300), nullable=True)
    year: Mapped[int | None] = mapped_column(Integer, nullable=True)
    isbn: Mapped[str | None] = mapped_column(String(20), nullable=True)
    embed: Mapped[dict] = mapped_column(JSON, default=dict)
    chapters: Mapped[list] = mapped_column(JSON, default=list)
    summary: Mapped[str | None] = mapped_column(Text, nullable=True)
    impact: Mapped[str | None] = mapped_column(Text, nullable=True)


class LessonResource(Base):
    __tablename__ = "lesson_resources"
    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    lesson_id: Mapped[str] = mapped_column(ForeignKey("lessons.id", ondelete="CASCADE"), index=True)
    resource_id: Mapped[str] = mapped_column(ForeignKey("resources.id", ondelete="CASCADE"), index=True)
    role: Mapped[str] = mapped_column(String(16))  # required | supplementary
    order: Mapped[int] = mapped_column(Integer)
    lesson: Mapped[Lesson] = relationship(back_populates="resource_links")
    resource: Mapped[Resource] = relationship()


class Exercise(Base):
    __tablename__ = "exercises"
    id: Mapped[str] = mapped_column(String(64), primary_key=True)
    lesson_id: Mapped[str] = mapped_column(ForeignKey("lessons.id", ondelete="CASCADE"), unique=True)
    data: Mapped[dict] = mapped_column(JSON)  # title, prompt, starter, expected, hints, solution, explanation, advanced
    lesson: Mapped[Lesson] = relationship(back_populates="exercise")


class Question(Base):
    __tablename__ = "questions"
